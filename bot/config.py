# bot/config.py
"""Настройки алгоритма скидок — оптимизировано под реальный рынок."""
# Процент скидки зависит от частоты появления машин за неделю в день.
# Частота (машин/день) → минимальный порог скидки (%)
# Проверяется сверху вниз: первое совпадение по частоте.
#
# Анализ базы показал:
# - 11.43 машин/день (Toyota Prius 2008) — максимум, очень популярная
# - 7.0 машин/день — 2-е место
# - Медианная частота ~0.43 машин/день (3 машины в неделю)
# - 70% всех комбинаций имеют частоту < 1.0 машин/день
#
# Рекомендация: для редких моделей (0.5 и ниже) порог должен быть мягким,
# иначе пользователь никогда их не увидит.
# Для популярных (2+) — строгий порог, там всегда есть выбор.

FREQUENCY_DISCOUNT = [
    (5.0, 12),   # 5+ машин в день → 12% (очень популярные: Prius, Cruze, 2107)
    (2.0, 10),   # 2-5 машин в день → 10% (популярные: Elantra, Astra, Transit)
    (0.5, 7),    # 0.5-2 машин в день → 7% (средние: большинство моделей)
    (0.1, 5),    # 0.1-0.5 машин в день → 5% (редкие: 1-3 в неделю)
    (0.0, 0),    # меньше 0.1 машин в день → 0% (эксклюзив: показываем всё)
]

# Минимальный порог скидки для всех (не ниже этого)
ABSOLUTE_MIN_DISCOUNT = 0

# Сколько дней смотрим для расчёта частоты
FREQUENCY_DAYS = 7